/* 当前档位 */
QL.ops.current = function () {
  var pv = QL.ops.stats.monthlyPV || 0, list = QL.ops.tiers;
  for (var i = 0; i < list.length; i++) {
    var t = list[i];
    if (pv >= t.min && (!t.max || pv < t.max)) return t;
  }
  return list[0];
};

/* 把数字凑成好看的价格：199 / 359 / 699 / 1299 / 19999 */
QL.ops.nicePrice = function (n) {
  if (n < 1000)  return Math.ceil(n / 10) * 10 - 1;
  if (n < 10000) return Math.ceil(n / 50) * 50 - 1;
  return Math.ceil(n / 100) * 100 - 1;
};

/* 基础价 → 当前档位实际价（带千分位） */
QL.ops.price = function (base, tierId) {
  var rate = QL.ops.current().rate;
  if (tierId) {
    var t = QL.byId ? QL.byId(QL.ops.tiers, tierId) : null;
    for (var i = 0; i < QL.ops.tiers.length; i++) {
      if (QL.ops.tiers[i].id === tierId) { t = QL.ops.tiers[i]; break; }
    }
    if (t) rate = t.rate;
  }
  return QL.ops.nicePrice(base * rate);
};

QL.ops.fmt = function (n) {
  var s = String(Math.round(n || 0)), out = '';
  while (s.length > 3) { out = ',' + s.slice(-3) + out; s = s.slice(0, -3); }
  return s + out;
};

/* 当前档位的单版位月曝光估算 */
QL.ops.impressions = function () {
  return Math.round((QL.ops.stats.monthlyPV || 0) * QL.ops.viewRate);
};

